import { describe, it, expect, afterEach } from 'vitest';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { execFileSync } from 'child_process';
import { projectConfigRepositoryAt } from '../../src/config/project-config.js';

// ---------------------------------------------------------------------------
// An upgrade must not delete committed agent files. A project.yaml written
// before rules.materializeAgentFiles existed was always materialized; while
// wairon-managed agent files are present it reads true, so the first save
// (doctor --fix) writes `true` down and the first lock keeps the files.
// ---------------------------------------------------------------------------

const roots: string[] = [];
function project(rules: string[] = []): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'wairon-mat-'));
  roots.push(root);
  fs.mkdirSync(path.join(root, '.wai'), { recursive: true });
  fs.writeFileSync(path.join(root, '.wai', 'project.yaml'), [
    'schemaVersion: 1.0.0', 'name: Legacy', 'targets:', '  - type: claude', '    outputDir: .claude/agents', '    enabled: true',
    ...(rules.length ? ['rules:', ...rules.map((r) => `  ${r}`)] : []),
    "createdAt: '2026-01-01T00:00:00.000Z'", "updatedAt: '2026-01-01T00:00:00.000Z'", '',
  ].join('\n'));
  return root;
}
function agentFile(root: string, dir: string, name: string, body = '# agent\n'): void {
  fs.mkdirSync(path.join(root, dir), { recursive: true });
  fs.writeFileSync(path.join(root, dir, name), body);
}

function git(root: string, ...args: string[]): void {
  execFileSync('git', args, { cwd: root, stdio: 'ignore', env: { ...process.env, GIT_TERMINAL_PROMPT: '0' } });
}
function gitRepo(root: string): void {
  git(root, 'init', '-q');
  git(root, 'config', 'user.name', 'test');
  git(root, 'config', 'user.email', 'test@localhost');
  git(root, 'config', 'core.autocrlf', 'false');
}

afterEach(() => {
  for (const r of roots.splice(0)) fs.rmSync(r, { recursive: true, force: true });
});

describe('materializeAgentFiles on a configuration that predates it', () => {
  it('reads true while wairon-managed agent files are present (by name)', () => {
    const root = project();
    agentFile(root, '.claude/agents', 'billing-owner.md');
    expect(projectConfigRepositoryAt(root).load()!.rules.materializeAgentFiles).toBe(true);
  });

  it('reads true for a managed file found by its marker, in any built-in target folder', () => {
    const root = project();
    agentFile(root, '.github/prompts', 'billing.prompt.md', '<!-- wairon:managed — generated by `wairon generate` -->\nbody\n');
    expect(projectConfigRepositoryAt(root).load()!.rules.materializeAgentFiles).toBe(true);
  });

  it('reads false with no managed agent file, and ignores hand-written ones', () => {
    const root = project();
    agentFile(root, '.claude/agents', 'my-notes.md', '# written by a person\n');
    expect(projectConfigRepositoryAt(root).load()!.rules.materializeAgentFiles).toBe(false);
  });

  it('a stated value always wins', () => {
    const root = project(['materializeAgentFiles: false']);
    agentFile(root, '.claude/agents', 'billing-owner.md');
    expect(projectConfigRepositoryAt(root).load()!.rules.materializeAgentFiles).toBe(false);
  });

  it('the first save writes true, not false', () => {
    const root = project();
    agentFile(root, '.claude/agents', 'billing-owner.md');
    const repo = projectConfigRepositoryAt(root);
    repo.setProjectType('library');
    const text = fs.readFileSync(path.join(root, '.wai', 'project.yaml'), 'utf8');
    expect(text).toMatch(/materializeAgentFiles: true/);
    expect(text).not.toMatch(/materializeAgentFiles: false/);
  });

  it('a save that cannot see the agent files leaves the setting unstated, so the project root still reads true', () => {
    // A family migration rehearses in a copy holding .wai/ alone, then copies
    // the configuration back: the copy must not record the schema default.
    const root = project();
    agentFile(root, '.cursor/rules', 'billing-owner.md');
    const rehearsal = fs.mkdtempSync(path.join(os.tmpdir(), 'wairon-mat-copy-'));
    roots.push(rehearsal);
    fs.mkdirSync(path.join(rehearsal, '.wai'), { recursive: true });
    fs.copyFileSync(path.join(root, '.wai', 'project.yaml'), path.join(rehearsal, '.wai', 'project.yaml'));
    expect(projectConfigRepositoryAt(rehearsal).setId('legacy')).toBe(true);
    const written = fs.readFileSync(path.join(rehearsal, '.wai', 'project.yaml'), 'utf8');
    expect(written).toMatch(/^id: legacy$/m);
    expect(written).not.toMatch(/materializeAgentFiles/);
    // Applied back to the project, it reads true from the files there.
    fs.copyFileSync(path.join(rehearsal, '.wai', 'project.yaml'), path.join(root, '.wai', 'project.yaml'));
    expect(projectConfigRepositoryAt(root).load()!.rules.materializeAgentFiles).toBe(true);
  });

  it('a project with no agent files keeps a stated false', () => {
    const root = project(['materializeAgentFiles: false']);
    projectConfigRepositoryAt(root).setProjectType('library');
    expect(fs.readFileSync(path.join(root, '.wai', 'project.yaml'), 'utf8')).toMatch(/materializeAgentFiles: false/);
  });
});

describe('materializeAgentFiles inference counts only the agent files git tracks', () => {
  it('a committed managed agent file reads true', () => {
    const root = project();
    gitRepo(root);
    agentFile(root, '.claude/agents', 'billing-owner.md');
    git(root, 'add', '-A');
    git(root, 'commit', '-q', '-m', 'agents');
    expect(projectConfigRepositoryAt(root).load()!.rules.materializeAgentFiles).toBe(true);
  });

  it('a staged (not yet committed) managed agent file reads true', () => {
    const root = project();
    gitRepo(root);
    agentFile(root, '.github/prompts', 'billing.prompt.md', '<!-- wairon:managed -->\nbody\n');
    git(root, 'add', '--', '.github/prompts');
    expect(projectConfigRepositoryAt(root).load()!.rules.materializeAgentFiles).toBe(true);
  });

  it('an ignored leftover does not switch materialization on, and a save leaves it unstated', () => {
    const root = project();
    gitRepo(root);
    fs.writeFileSync(path.join(root, '.gitignore'), '.claude/\n');
    agentFile(root, '.claude/agents', 'billing-owner.md');
    const repo = projectConfigRepositoryAt(root);
    expect(repo.load()!.rules.materializeAgentFiles).toBe(false);
    repo.setProjectType('library');
    expect(fs.readFileSync(path.join(root, '.wai', 'project.yaml'), 'utf8')).not.toMatch(/materializeAgentFiles/);
  });

  it('an untracked managed agent file does not switch materialization on', () => {
    const root = project();
    gitRepo(root);
    agentFile(root, '.cursor/rules', 'billing-owner.md');
    agentFile(root, '.github/prompts', 'billing.prompt.md', '<!-- wairon:managed -->\nbody\n');
    expect(projectConfigRepositoryAt(root).load()!.rules.materializeAgentFiles).toBe(false);
  });

  it('a tracked hand-written file beside an untracked managed one still reads false', () => {
    const root = project();
    gitRepo(root);
    agentFile(root, '.claude/agents', 'my-notes.md', '# written by a person\n');
    git(root, 'add', '-A');
    git(root, 'commit', '-q', '-m', 'notes');
    agentFile(root, '.claude/agents', 'billing-owner.md');
    expect(projectConfigRepositoryAt(root).load()!.rules.materializeAgentFiles).toBe(false);
  });

  it('outside any git work tree, presence decides (the files may be all a person has)', () => {
    const root = project();
    expect(fs.existsSync(path.join(root, '.git'))).toBe(false);
    agentFile(root, '.claude/agents', 'billing-owner.md');
    expect(projectConfigRepositoryAt(root).load()!.rules.materializeAgentFiles).toBe(true);
  });
});
